"""Builds @vieo-io/fonts from the upstream releases in sources.json, or checks what was built.

    python3 -I scripts/build.py --download DIR   fetch each source into DIR, an empty folder, then build
    python3 -I scripts/build.py --from DIR       build from sources fetched into DIR before
    python3 -I scripts/build.py --check          check fonts.css, the files, their features, and the licences

Needs fontTools and brotli.
"""

import argparse
import json
import re
import shutil
import sys
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

PACKAGE = Path(__file__).resolve().parent.parent
SOURCES = PACKAGE / "sources.json"
CSS = PACKAGE / "fonts.css"
FONTS = PACKAGE / "fonts"

HEADER = "/* Generated by scripts/build.py from sources.json. Each family's licence is beside this file. */\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--download", type=Path)
    mode.add_argument("--from", dest="source_dir", type=Path)
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = json.loads(SOURCES.read_text())
    if args.check:
        problems = check(sources)
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    if args.download:
        download(sources, args.download)
    build(sources, args.download or args.source_dir)
    return 0


def build(sources: dict, source_dir: Path) -> None:
    FONTS.mkdir(exist_ok=True)
    faces = []
    for family in sources["families"]:
        font = TTFont(source_dir / f"{slug(family)}.ttf", lazy=False)
        options = subset.Options()
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.notdef_outline = True
        options.hinting = False
        options.flavor = "woff2"
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=subset.parse_unicodes(sources["subset"]))
        subsetter.subset(font)
        font.flavor = "woff2"
        font.save(FONTS / family["file"])
        family["version"] = font["name"].getDebugName(5)
        shutil.copyfile(source_dir / f"OFL-{slug(family)}.txt", PACKAGE / f"OFL-{slug(family)}.txt")
        faces.append(face(family, font))
        print(f"{family['file']}: {(FONTS / family['file']).stat().st_size // 1024} KB, {family['version']}")
    SOURCES.write_text(json.dumps(sources, indent="\t") + "\n")
    CSS.write_text(HEADER + "\n".join(faces))


def check(sources: dict) -> list[str]:
    """fonts.css, the files it names, their family names and features, and the licences agree with sources.json."""
    problems = []
    faces = dict(
        (file, name)
        for name, file in re.findall(
            r"font-family:\s*[\"']([^\"']+)[\"'];\s*src:\s*url\([\"']\./fonts/([^\"']+)[\"']\)", CSS.read_text()
        )
    )
    if not faces:
        problems.append("fonts.css names no font files")
    for file in faces:
        if not (FONTS / file).exists():
            problems.append(f"fonts.css names {file}, which is missing")
    for family in sources["families"]:
        if family["file"] not in faces:
            problems.append(f"fonts.css has no face for {family['family']}")
        elif faces[family["file"]] != family["family"]:
            problems.append(f"{family['file']} is named {faces[family['file']]} in fonts.css, not {family['family']}")
        path = FONTS / family["file"]
        if not path.exists():
            problems.append(f"{path.name} is missing")
            continue
        font = TTFont(path)
        kept = {record.FeatureTag for record in font["GSUB"].table.FeatureList.FeatureRecord}
        lost = [feature for feature in family["features"] if feature not in kept]
        if lost:
            problems.append(f"{path.name} lost {', '.join(lost)}")
        licence = PACKAGE / f"OFL-{slug(family)}.txt"
        if not licence.exists() or "SIL OPEN FONT LICENSE" not in licence.read_text().upper():
            problems.append(f"{family['family']} has no OFL text at {licence.name}")
    return problems


def download(sources: dict, into: Path) -> None:
    into.mkdir(parents=True, exist_ok=True)
    for family in sources["families"]:
        urllib.request.urlretrieve(family["source"], into / f"{slug(family)}.ttf")
        urllib.request.urlretrieve(family["licence"], into / f"OFL-{slug(family)}.txt")


def face(family: dict, font: TTFont) -> str:
    axes = {axis.axisTag: axis for axis in font["fvar"].axes} if "fvar" in font else {}
    weight = f"{axes['wght'].minValue:g} {axes['wght'].maxValue:g}" if "wght" in axes else "400"
    return (
        "@font-face {\n"
        f'\tfont-family: "{family["family"]}";\n'
        f'\tsrc: url("./fonts/{family["file"]}") format("woff2");\n'
        f"\tfont-weight: {weight};\n"
        "\tfont-style: normal;\n"
        "\tfont-display: swap;\n"
        "}\n"
    )


def slug(family: dict) -> str:
    return family["file"].removesuffix(".woff2")


if __name__ == "__main__":
    sys.exit(main())
